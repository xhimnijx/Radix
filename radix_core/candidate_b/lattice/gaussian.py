"""Discrete Gaussian, sampled from a shared table.

The old sampler rounded a *continuous* Gaussian. Two problems, and the second is the
one that matters:

1. It is not the object Lemma A.6 is stated for.
2. It is **not portable**. Python and Rust each round a float Gaussian, and `libm`
   disagreement makes them different distributions — so the rejection argument applies
   to neither, and the cross-language acceptance test compares two different protocols
   while appearing to compare one.

This module reads a table generated by `experiments/make_gaussian_tables.py`. The Rust
implementation `include_bytes!`s the *same file*, so the two cannot drift by accident:
there is one distribution, stored once.

The table covers `|x| <= 12 sigma`; beyond that the tail is about 2^-107.8 per
coefficient, which aggregates over the 4224 coefficients of a response to about
2^-101.8 -- below the paper's 2^-100 HVZK clause, so the truncation no longer limits it.

Sampling is integer-only at runtime: a 32-bit uniform picks a magnitude by binary
search over the cumulative table, and one bit picks the sign. `from_uniform` is a pure
function of its two inputs, which is what makes the cross-language test meaningful.
"""

from __future__ import annotations

import pathlib
import struct

MAGIC = b"RDXGAUSS"
VERSION = 1
#: magic 8 + version 4 + sigma 8 + count 4
HEADER = 24
TABLES = pathlib.Path(__file__).with_name("tables")

_cache: dict[int, tuple[float, tuple[int, ...]]] = {}


def table(width: int) -> tuple[float, tuple[int, ...]]:
    """Return `(sigma, cumulative)` for the mask width, loading it once."""
    if width in _cache:
        return _cache[width]

    path = TABLES / f"gaussian_w{width}.bin"
    try:
        payload = path.read_bytes()
    except OSError as error:
        raise RuntimeError(
            f"missing Gaussian table {path}; run experiments/make_gaussian_tables.py"
        ) from error

    if payload[:8] != MAGIC:
        raise RuntimeError(f"{path} is not a Gaussian table")
    version, sigma, count = struct.unpack_from("<IdI", payload, 8)
    if version != VERSION:
        raise RuntimeError(f"{path} has version {version}, expected {VERSION}")
    if len(payload) != HEADER + 4 * count:
        raise RuntimeError(f"{path} is truncated")

    entries = struct.unpack_from("<" + "I" * count, payload, HEADER)
    if entries[-1] != (1 << 32) - 1:
        raise RuntimeError(f"{path} does not end with the sentinel")
    _cache[width] = (sigma, entries)
    return sigma, entries


def from_uniform(width: int, uniform: int, sign: int) -> int:
    """Map a 32-bit uniform and a sign bit to one sample.

    Pure, and identical to `gaussian::from_uniform` in Rust. Kept deliberately free of
    any RNG so the cross-language test can compare it directly.
    """
    if not 0 <= uniform < (1 << 32):
        raise ValueError("uniform must be a 32-bit value")
    if sign not in (0, 1):
        raise ValueError("sign must be 0 or 1")

    _sigma, cumulative = table(width)
    low, high = 0, len(cumulative) - 1
    while low < high:
        middle = (low + high) // 2
        if cumulative[middle] > uniform:
            high = middle
        else:
            low = middle + 1
    return -low if sign else low


def sample(rng, width: int) -> int:
    """One integer from the discrete Gaussian for this width."""
    return from_uniform(width, rng.getrandbits(32), rng.getrandbits(1))


def sigma(width: int) -> float:
    """The standard deviation the table was built for."""
    return table(width)[0]


def max_magnitude(width: int) -> int:
    """The truncation point, 8 sigma."""
    return len(table(width)[1]) - 1
