"""Prime-order group used by the Candidate-B prototype.

This is a Schnorr group over a 256-bit safe prime p = 2q + 1. A hidden-order
group is *not* post-quantum: Shor breaks it. It exists here so the Candidate-B
protocol machinery (rings, linkable tags, anchored membership, atomic state) can
be built and tested end to end before the lattice signature is swapped in. The
launch gate refuses this backend for mainnet (no post-quantum assumptions).

Parameter provenance: generated by `scripts/`-style Miller-Rabin search and
verified by `validate_parameters()` in the tests. p and q are checked for
probable primality, p = 2q + 1, and ord(g) = q.
"""

from __future__ import annotations

from hashlib import shake_256

P = 85405822536017922297948551674782417770288849586462407111595805459787717200847
Q = 42702911268008961148974275837391208885144424793231203555797902729893858600423
G = 2

SCALAR_BYTES = 32
DOMAIN = b"RADIX/B/GROUP/V1"


def _shake(*parts: bytes) -> bytes:
    digest = shake_256()
    digest.update(DOMAIN)
    for part in parts:
        digest.update(len(part).to_bytes(4, "little"))
        digest.update(part)
    return digest.digest(64)


def hash_to_scalar(*parts: bytes) -> int:
    """Map labelled bytes to Z_q. Domain-separated and collision resistant."""
    return int.from_bytes(_shake(b"scalar", *parts), "little") % Q


def hash_to_point(*parts: bytes) -> int:
    """Map labelled bytes to a non-identity element of the order-q subgroup.

    Try-and-increment: square the candidate to force it into the quadratic-residue
    subgroup (order q for a safe prime). Deterministic in the input.
    """
    for counter in range(256):
        candidate = int.from_bytes(
            _shake(b"point", *parts, counter.to_bytes(2, "little")), "little"
        ) % P
        if candidate < 2:
            continue
        point = pow(candidate, 2, P)
        if point in (0, 1):
            continue
        return point
    raise RuntimeError("hash_to_point failed after 256 attempts")


def scalar_mul(scalar: int) -> int:
    """g^scalar, reduced into the subgroup order."""
    return pow(G, scalar % Q, P)


def point_pow(point: int, scalar: int) -> int:
    """point^scalar, reduced into the subgroup order."""
    _require_point(point)
    return pow(point, scalar % Q, P)


def point_mul(left: int, right: int) -> int:
    _require_point(left)
    _require_point(right)
    return (left * right) % P


def _require_point(point: int) -> None:
    if type(point) is not int or not 2 <= point < P:
        raise ValueError("group element must be an integer in [2, p-1]")


def is_valid_point(point: int) -> bool:
    try:
        _require_point(point)
    except ValueError:
        return False
    return pow(point, Q, P) == 1


def encode_scalar(scalar: int) -> bytes:
    if type(scalar) is not int or not 0 <= scalar < Q:
        raise ValueError("scalar out of range")
    return scalar.to_bytes(SCALAR_BYTES, "big")


def decode_scalar(data: bytes) -> int:
    if type(data) is not bytes or len(data) != SCALAR_BYTES:
        raise ValueError("scalar encoding must be exactly 32 bytes")
    value = int.from_bytes(data, "big")
    if value >= Q:
        raise ValueError("non-canonical scalar encoding")
    return value


def encode_point(point: int) -> bytes:
    _require_point(point)
    return point.to_bytes(SCALAR_BYTES, "big")


def decode_point(data: bytes) -> int:
    if type(data) is not bytes or len(data) != SCALAR_BYTES:
        raise ValueError("point encoding must be exactly 32 bytes")
    point = int.from_bytes(data, "big")
    _require_point(point)
    return point


def validate_parameters() -> None:
    """Cheap structural checks; primality is asserted in the test suite."""
    if P % 2 != 1 or Q != (P - 1) // 2:
        raise ValueError("p must be an odd safe prime with q = (p-1)/2")
    if pow(G, Q, P) != 1 or pow(G, 2, P) == 1:
        raise ValueError("g must generate the order-q subgroup")
